/** 把学情摘要拼进教师端系统提示词 */
export function buildTeacherSystemPrompt(digestText: string): string {
  if (!digestText.trim()) {
    return `${TEACHER_SYSTEM_PROMPT}

【学情数据】
（当前没有采集到任何学情数据。请告诉教师需要先在学生端完成诊断、作业或提问，才能进行分析。）`;
  }
  return `${TEACHER_SYSTEM_PROMPT}

【学情数据】
${digestText}`;
}

/** 把检索到的资料拼进系统提示词 */
export function buildSystemPrompt(sources: RetrievedSource[]): string {
  if (sources.length === 0) {
    return `${SYSTEM_PROMPT}

【课程资料】
（本次没有检索到匹配的课程资料，请按电工学通识回答，并提醒学生核对教材。）`;
  }
  const body = sources
    .map((s, i) => `--- 资料 ${i + 1}｜${s.source} ---\n${s.text}`)
    .join("\n\n");
  return `${SYSTEM_PROMPT}

【课程资料】
${body}`;
}
